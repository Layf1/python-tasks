#Даны два круга с общим центром и радиусами R1 и R2 (R1 > R2). 
#Найти площади этих кругов S1 и S2, а также площадь S3 кольца, внешний радиус которого равен R1, а внутренний радиус равен R2: S1 = π·(R1)², S2 = π·(R2)², S3 = S1 − S2.
#В качестве значения π использовать 3.14.
R1 = float(abs())
R2 = float(abs())
S1 = 3.14 * (R1 ** 2)
S2 = 3.14 * (R2 ** 2)
S3 = S1 - S2 