#Дано целое число N (> 0). Найти двойной факториал N: N!! = N·(N−2)·(N−4)·… (последний сомножитель равен 2, если N — четное, и 1, если N — нечетное).
#Чтобы избежать целочисленного переполнения, вычислять это произведение с помощью вещественной переменной и вывести его как вещественное число
n = float(input())  
double_factorial = 1.0

while n > 1:
    double_factorial *= n
    n -= 2

print(double_factorial)