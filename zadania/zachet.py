N = [20, 12, 13, 17, 14, 15, 1, 2, 6, 8, 9, 10, -8, -6, 5, 0, 4, 11, 16, 15]
a = sum(N) / 20
count = 0
for i in N:
    if i > a:
        count +=1
    else:
        count +=0

print("Максиальное число из списка", max(N))
print("кол-во элементов что больше среднего арефметического", count)

